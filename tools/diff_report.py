#!/usr/bin/env python3
"""Instruction-level diff of matched-but-changed functions, S08 -> S25.

Usage: python diff_report.py match.csv S25.BIN s25.sym S08.BIN s08.sym out.md
"""
import csv
import difflib
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from match_versions import analyze, tokens

mcsv, a_img, a_sym, b_img, b_sym, out = sys.argv[1:7]
A, Af = analyze(a_img, a_sym)
B, Bf = analyze(b_img, b_sym)


def lines(d, body, masked=True):
    r = []
    orig = d.name_code
    if masked:
        d.name_code = lambda a: "@"
    try:
        for a in body:
            r.append(d.fmt_insn(d.insns[a]))
    finally:
        d.name_code = orig
    return r


def norm(s):
    # hide pure address differences in labels
    import re
    return re.sub(r"\b[fl]_[0-9A-F]{4}\b", "@", s)


rows = list(csv.DictReader(open(mcsv)))
with open(out, "w", encoding="utf-8") as w:
    w.write("# PM2525 firmware S08 -> S25 function diff\n\n")
    w.write("Generated by `tools/diff_report.py`. Code-address differences (labels) are masked; only real\n"
            "instruction/operand changes are shown. `-` = S08, `+` = S25.\n\n")
    changed = [r for r in rows if r["method"] not in ("exact", "exact-ordered", "unmatched")]
    unmatched = [r for r in rows if r["method"] == "unmatched"]
    w.write("## Summary\n\n- S25 functions: %d\n- identical in S08: %d\n- changed: %d\n- new in S25 (no S08 match): %d\n\n" % (
        len(rows), sum(r["method"] in ("exact", "exact-ordered") for r in rows), len(changed), len(unmatched)))
    w.write("## Changed functions\n\n")
    for r in changed:
        a, b = int(r["s25_addr"], 16), int(r["s08_addr"], 16)
        la, lb = lines(A, Af[a]), lines(B, Bf[b])
        diff = [x for x in difflib.unified_diff([norm(x) for x in lb], [norm(x) for x in la], lineterm="", n=1)][2:]
        if not diff:
            continue
        w.write("### %s (S25 %04X, S08 %04X) %s %s, %s -> %s bytes\n\n```diff\n" % (
            r["s25_name"], a, b, r["method"], r["score"], r["s08_size"], r["s25_size"]))
        w.write("\n".join(diff[:80]))
        if len(diff) > 80:
            w.write("\n... (%d more lines)" % (len(diff) - 80))
        w.write("\n```\n\n")
    w.write("## New in S25\n\n")
    for r in unmatched:
        a = int(r["s25_addr"], 16)
        w.write("### %s (S25 %04X, %s bytes)\n\n```asm\n%s\n```\n\n" % (
            r["s25_name"], a, r["s25_size"], "\n".join(lines(A, Af[a], masked=False))))
print("written", out)
