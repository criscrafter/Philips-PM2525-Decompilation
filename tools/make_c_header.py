#!/usr/bin/env python3
"""Write fw/c/pm2525_fw.h: the firmware's SFRs, IRAM variables, bits and XDATA variables as SDCC
declarations at their fixed addresses (no storage is allocated; C code shares the firmware's RAM).

Usage: python make_c_header.py tools/s25.sym fw/c/pm2525_fw.h
"""
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import dis8051 as D8

syms = D8.load_syms(sys.argv[1])
L = ["/* pm2525_fw.h - generated by tools/make_c_header.py from tools/s25.sym. Do not edit; rerun it.",
     " * Variables of the original firmware at their fixed addresses, for C code linked into it.",
     " * IRAM is completely used by the firmware: never declare new __data/__idata variables in C",
     " * (the build fails if you do); use __xdata ones, which go to the free XDATA 0x07A3-0x07FC. */",
     "#ifndef PM2525_FW_H", "#define PM2525_FW_H", "", "/* ---- SFRs ---- */"]
for v, n in sorted(D8.SFR.items()):
    L.append("__sfr __at(0x%02X) %s;" % (v, n))
L += ["", "/* ---- SFR bits ---- */"]
for v, n in sorted(D8.SFRBITS.items()):
    L.append("__sbit __at(0x%02X) %s;" % (v, n))
seen = set(D8.SFR.values()) | set(D8.SFRBITS.values())


def ok(n):
    n = re.sub(r"\W", "_", n)
    if n in seen:
        n = n + "_"
    seen.add(n)
    return n


L += ["", "/* ---- internal RAM (bytes) ---- */"]
for v, (n, c) in sorted(syms["data"].items()):
    L.append("__data __at(0x%02X) unsigned char %s;%s" % (v, ok(n), ("   /* %s */" % c) if c else ""))
L += ["", "/* ---- bit variables (bit address = (byte-0x20)*8 + bit) ---- */"]
for v, (n, c) in sorted(syms["bit"].items()):
    L.append("__bit __at(0x%02X) %s;%s" % (v, ok(n), ("   /* %s */" % c) if c else ""))
L += ["", "/* ---- external RAM (battery-backed 6116, 0x0000-0x07FF) ---- */"]
for v, (n, c) in sorted(syms["xdata"].items()):
    L.append("__xdata __at(0x%04X) unsigned char %s;%s" % (v, ok("x_" + n), ("   /* %s */" % c) if c else ""))
L += ["", "#endif", ""]
open(sys.argv[2], "w", encoding="utf-8", newline="\n").write("\n".join(L))
print("%s: %d declarations" % (sys.argv[2], len(L)))
