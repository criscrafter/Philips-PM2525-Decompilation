#!/usr/bin/env python3
"""Turn dis8051.py JSON + symbol file into a Ghidra seeds file for SeedFunctions.java.

Usage: python make_seeds.py pass.json symbols.sym seeds.txt
"""
import sys

js_path, sym_path, out_path = sys.argv[1:4]
import json

js = json.load(open(js_path))
names = {}
for line in open(sym_path, encoding="utf-8"):
    line = line.split("#", 1)[0].split()
    if len(line) >= 3 and line[0] == "code":
        names[int(line[1], 16)] = line[2]

with open(out_path, "w") as w:
    w.write("# generated by make_seeds.py\n")
    for base, (stride, n, src) in js["jtabs"].items():
        b = int(base, 16)
        ents = [b + stride * i for i in range(n)]
        for e in ents:
            w.write("code %04X\n" % e)
        if src is not None:
            w.write("jtab %04X %s\n" % (src, " ".join("%04X" % e for e in ents)))
    for a, f in sorted(js["functions"].items()):
        ai = int(a, 16)
        if ai == 0x0003:          # reset falls through NOPs into this LJMP: not a separate function
            w.write("code 0003\nlabel 0003 vec_0003_ljmp_start\n")
            continue
        name = names.get(ai, f["name"])
        w.write("func %04X %s\n" % (ai, name))
    for a, n in sorted(names.items()):
        if "%04X" % a not in js["functions"]:
            kind = "func" if n.startswith(("isr_", "main_loop", "i2c")) else "label"
            w.write("%s %04X %s\n" % (kind, a, n))
    # data / bit / xdata labels for Ghidra (INTMEM, BITS, EXTMEM spaces)
    space = {"data": "INTMEM", "bit": "BITS", "xdata": "EXTMEM"}
    for line in open(sym_path, encoding="utf-8"):
        f = line.split("#", 1)[0].split()
        if len(f) >= 3 and f[0] in space:
            w.write("slabel %s %X %s\n" % (space[f[0]], int(f[1], 16), f[2]))
print("seeds written:", out_path)
